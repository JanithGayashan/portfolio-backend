import logging
import traceback
from datetime import datetime
from fastapi import APIRouter, HTTPException, status
from pydantic import BaseModel
from langchain_core.messages import HumanMessage, AIMessage

# 1. IMPORTS
from app.services.agent.graph import graph
from app.db.database import get_client  

logger = logging.getLogger(__name__)
router = APIRouter()

# 2. SCHEMA
class ChatRequest(BaseModel):
    message: str
    thread_id: str

@router.post("/message")
async def chat_endpoint(request: ChatRequest):
    try:
        # 3. Setup DB Connection
        db_client = get_client()
        db = db_client["portfolio_chatbot_db"]
        collection = db["chat_history"]

        # 4. Fetch historical messages from MongoDB
        history_docs = list(collection.find({"thread_id": request.thread_id}))
        
        formatted_history = []
        for doc in history_docs:
            if doc.get("sender") == "user":
                formatted_history.append(HumanMessage(content=doc.get("text", "")))
            elif doc.get("sender") == "bot":
                formatted_history.append(AIMessage(content=doc.get("text", "")))

        # 5. Append the brand new user message to the historical chain
        current_user_message = HumanMessage(content=request.message)
        full_message_history = formatted_history + [current_user_message]

        # 6. Construct the initial state for the Plan and Execute graph
        initial_state = {
            "messages": full_message_history,
            "current_user_input": request.message,
            "plan": [],
            "past_steps": []
        }

        # 7. Invoke the graph 
        config = {"configurable": {"thread_id": request.thread_id}}
        final_state = await graph.ainvoke(initial_state, config=config)

        # 8. EXTRACT STRUCTURED FINAL RESPONSE
        # We extract the clean dictionary generated by the Re-Planner node!
        final_data = final_state.get("final_response", {})

        # Fallback safety: If the graph failed to produce structured data for some reason
        if not final_data:
            final_messages = final_state.get("messages", [])
            fallback_text = final_messages[-1].content if final_messages else "I encountered an error."
            final_data = {
                "reply": fallback_text,
                "ui_action": "NONE",
                "target_route": ""
            }

        # 9. Map the structured data to variables
        final_bot_response = final_data.get("reply", "I encountered an error.")
        action_type = final_data.get("ui_action", "NONE")
        target_route = final_data.get("target_route", "") or ""

        # 10. POST-RESPONSE PERSISTENCE: Save to MongoDB
        timestamp = datetime.utcnow()
        collection.insert_many([
            {
                "thread_id": request.thread_id,
                "sender": "user",
                "text": request.message,
                "timestamp": timestamp
            },
            {
                "thread_id": request.thread_id,
                "sender": "bot",
                "text": final_bot_response,
                "timestamp": timestamp
            }
        ])

        # 11. Return perfectly formatted data directly to your ChatWidget.tsx
        return {
            "reply": final_bot_response,
            "action": action_type,
            "target": target_route
        }

    except Exception as e:
        logger.error("🔥 EXCEPTION ENCOUNTERED IN CHAT LIFECYCLE 🔥")
        traceback.print_exc()
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, 
            detail=str(e)
        )